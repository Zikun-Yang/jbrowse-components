#!/usr/bin/env node
/**
 * Regenerate `FORK_MANIFEST.md`: every file this fork adds, modifies or deletes
 * relative to upstream, with the upstream sync point spelled out.
 *
 * `FORK.md` explains *why* the fork has these changes and judges what upstream
 * would take; this file is the mechanical half, so "did FORK.md list everything?"
 * is answered by a command instead of by reading 900 paths.
 *
 * Usage:
 *   node scripts/fork-manifest.mjs           # write FORK_MANIFEST.md
 *   node scripts/fork-manifest.mjs --check   # exit 1 if it is out of date
 *
 * After merging upstream, bump UPSTREAM_BASE (see the rebase checklist in
 * FORK.md) and rerun this.
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Last commit from upstream `GMOD/jbrowse-components` that this fork has merged.
 * Everything after it is fork work. Update this when you merge upstream, then
 * rerun the script — the diff shrinks and any file that upstream has adopted can
 * come out of FORK.md.
 */
const UPSTREAM_BASE = 'ffe7382b8'
const OUTPUT = 'FORK_MANIFEST.md'
const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
)

function git(args) {
  return execFileSync('git', args, {
    cwd: repoRoot,
    encoding: 'utf8',
  }).trimEnd()
}

function areaOf(file) {
  const parts = file.split('/')
  if (parts.length === 1) {
    return '(root)'
  }
  if (['packages', 'products', 'plugins'].includes(parts[0])) {
    return `${parts[0]}/${parts[1]}`
  }
  if (parts[0] === 'website' && parts[1] === 'docs') {
    return `website/docs/${parts[2] === undefined ? '' : parts[2].endsWith('.md') ? '(pages)' : parts[2]}`
  }
  if (parts[0] === 'website') {
    return 'website (other)'
  }
  if (parts[0] === 'component_tests' || parts[0] === 'test_data') {
    return `${parts[0]}/${parts[1] ?? ''}`
  }
  return parts[0]
}

const statusLetters = { A: 'A', M: 'M', D: 'D', R: 'R', C: 'C', T: 'M' }

const raw = git([
  'diff',
  '--name-status',
  '--find-renames',
  `${UPSTREAM_BASE}..HEAD`,
  '--',
  '.',
  ':(exclude).multica',
  ':(exclude).pi',
])

const rows = raw
  .split('\n')
  .filter(Boolean)
  .map(line => {
    const fields = line.split('\t')
    const status = fields[0][0]
    if (status === 'R' || status === 'C') {
      return { status, from: fields[1], file: fields[2] }
    }
    return { status, file: fields[1] }
  })

const groups = new Map()
for (const row of rows) {
  const area = areaOf(row.file)
  if (!groups.has(area)) {
    groups.set(area, [])
  }
  groups.get(area).push(row)
}

const counts = rows.reduce((acc, row) => {
  const letter = statusLetters[row.status] ?? row.status
  acc[letter] = (acc[letter] ?? 0) + 1
  return acc
}, {})

const areas = [...groups.keys()].sort()

const body = [
  '# Fork manifest',
  '',
  '<!-- generated by `node scripts/fork-manifest.mjs` — do not edit by hand -->',
  '',
  `Files this fork changes relative to upstream, measured from the last merged`,
  `upstream commit \`${UPSTREAM_BASE}\`.`,
  '',
  `Totals: ${rows.length} paths — added ${counts.A ?? 0}, modified ${counts.M ?? 0}, ` +
    `deleted ${counts.D ?? 0}${counts.R ? `, renamed ${counts.R}` : ''}.`,
  '',
  'Read this together with [FORK.md](./FORK.md), which explains the changes and',
  'judges what upstream would accept. Regenerate with',
  '`node scripts/fork-manifest.mjs`; `--check` fails when it is stale.',
  '',
]

for (const area of areas) {
  const entries = groups.get(area).sort((a, b) => a.file.localeCompare(b.file))
  body.push(`## ${area} (${entries.length})`, '')
  for (const entry of entries) {
    const letter = statusLetters[entry.status] ?? entry.status
    if (entry.from) {
      body.push(`- \`${letter}\` \`${entry.file}\` (from \`${entry.from}\`)`)
    } else {
      body.push(`- \`${letter}\` \`${entry.file}\``)
    }
  }
  body.push('')
}

const output = `${body.join('\n').trimEnd()}\n`
const target = path.join(repoRoot, OUTPUT)

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (current !== output) {
    console.error(
      `${OUTPUT} is out of date. Run: node scripts/fork-manifest.mjs`,
    )
    process.exit(1)
  }
  console.log(`${OUTPUT} is up to date (${rows.length} paths).`)
} else {
  fs.writeFileSync(target, output)
  console.log(`wrote ${OUTPUT}: ${rows.length} paths in ${areas.length} areas`)
}
