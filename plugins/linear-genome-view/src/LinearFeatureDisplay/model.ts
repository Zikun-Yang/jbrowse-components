/**
 * Maximum number of feature detail responses kept per display. Feature details
 * are immutable per track instance, so a small LRU is enough to make moving
 * the mouse back and forth over a dense track free of RPC calls.
 */
const MAX_FEATURE_DETAILS_CACHE = 100

/**
 * Track overrides of renderer config slots, shared by every feature display.
 * Getter, action, rendererConfig and snapshot plumbing for each entry is
 * generated by ./trackOverrides.ts so a new setting only needs the table entry
 * and the `trackXxx` property on the model.
 */
export const FEATURE_DISPLAY_TRACK_OVERRIDES = [
  {
    trackProp: 'trackShowLabels',
    getter: 'showLabels',
    slot: 'showLabels',
    action: 'toggleShowLabels',
    kind: 'toggle',
  },
  {
    trackProp: 'trackShowDescriptions',
    getter: 'showDescriptions',
    slot: 'showDescriptions',
    action: 'toggleShowDescriptions',
    kind: 'toggle',
  },
  {
    trackProp: 'trackDisplayMode',
    getter: 'displayMode',
    slot: 'displayMode',
    action: 'setDisplayMode',
    kind: 'set',
  },
  {
    trackProp: 'trackMaxHeight',
    getter: 'maxHeight',
    slot: 'maxHeight',
    action: 'setMaxHeight',
    kind: 'set',
  },
] as const satisfies readonly TrackOverride[]

/**
 * Getters generated from FEATURE_DISPLAY_TRACK_OVERRIDES. Declared as an
 * interface so call sites stay typed and so the state model docs keep listing
 * them (the runtime implementation is generated by trackOverrideViews).
 */
interface FeatureDisplayOverrideViews {
  /**
   * #getter
   * Whether to show feature labels. Falls back to renderer.showLabels when the
   * track override is not set
   */
  readonly showLabels: boolean
  /**
   * #getter
   * Whether to show feature descriptions. Falls back to
   * renderer.showDescriptions when the track override is not set
   */
  readonly showDescriptions: boolean
  /**
   * #getter
   * Display mode (normal, compact, reducedRepresentation, collapse). Falls
   * back to renderer.displayMode when the track override is not set
   */
  readonly displayMode: string
  /**
   * #getter
   * Maximum layout height. Falls back to renderer.maxHeight when the track
   * override is not set
   */
  readonly maxHeight: number
}

/** Actions generated from FEATURE_DISPLAY_TRACK_OVERRIDES */
interface FeatureDisplayOverrideActions {
  /**
   * #action
   * Toggle whether feature labels are shown
   */
  toggleShowLabels(): void
  /**
   * #action
   * Toggle whether feature descriptions are shown
   */
  toggleShowDescriptions(): void
  /**
   * #action
   * Set the display mode of the track
   */
  setDisplayMode(val: string): void
  /**
   * #action
   * Set the maximum layout height of the track
   */
  setMaxHeight(val?: number): void
}

const SetMaxHeightDialog = lazy(
  () => import('./components/SetMaxHeightDialog.tsx'),
)
const AddFiltersDialog = lazy(() => import('./components/AddFiltersDialog.tsx'))

/**
 * #stateModel LinearFeatureDisplay
 * #category display
 * Base model for feature displays. Provides labels, descriptions, display modes,
 * filters, etc. Does not include gene glyph functionality.
 *
 * extends
 * - [BaseLinearDisplay](../baselineardisplay)
 */
function stateModelFactory(configSchema: AnyConfigurationSchemaType) {
  return types
    .compose(
      'LinearFeatureDisplay',
      BaseLinearDisplay,
      types.model({
        /**
         * #property
         */
        type: types.literal('LinearFeatureDisplay'),
        /**
         * #property
         */
        trackShowLabels: types.maybe(types.boolean),
        /**
         * #property
         */
        trackShowDescriptions: types.maybe(types.boolean),
        /**
         * #property
         */
        trackDisplayMode: types.maybe(types.string),
        /**
         * #property
         */
        trackMaxHeight: types.maybe(types.number),
        /**
         * #property
         */
        configuration: ConfigurationReference(configSchema),
        /**
         * #property
         */
        jexlFiltersSetting: types.maybe(types.array(types.string)),
      }),
    )
    .volatile(() => ({
      /**
       * #volatile
       * Stores the feature under the mouse cursor, fetched asynchronously
       * via CoreGetFeatureDetails RPC to avoid serializing all features
       */
      featureUnderMouseVolatile: undefined as Feature | undefined,
      /**
       * #volatile
       * LRU cache of feature details fetched via CoreGetFeatureDetails,
       * keyed by top-level feature id. Not observable (plain Map).
       */
      featureDetailsCache: new Map<string, Feature>(),
      /**
       * #volatile
       * In-flight feature detail requests keyed by feature id so that rapid
       * hover/click on the same feature does not fire duplicate RPCs.
       */
      pendingFeatureDetails: new Map<string, Promise<Feature | undefined>>(),
    }))
    .views(self => {
      const views = {
        /**
         * #method
         */
        activeFilters(): string[] {
          // config jexlFiltersSetting are deferred evaluated so they are prepended with
          // jexl at runtime rather than being stored with jexl in the config
          return (
            toJS(self.jexlFiltersSetting) ??
            getConf(self, 'jexlFilters').map((r: string) => `jexl:${r}`)
          )
        },
        /**
         * #getter
         */
        get rendererTypeName() {
          return getConf(self, ['renderer', 'type'])
        },

        /**
         * #getter
         */
        get sequenceAdapter() {
          const { assemblyManager } = getSession(self)
          const track = getParent<{ configuration: AnyConfigurationModel }>(
            self,
            2,
          )
          const assemblyNames = readConfObject(
            track.configuration,
            'assemblyNames',
          ) as string[]
          const assembly = assemblyManager.get(assemblyNames[0]!)
          return assembly
            ? getConf(assembly, ['sequence', 'adapter'])
            : undefined
        },

        /**
         * #getter
         * Track overrides merged into rendererConfig. Subclasses extend this
         * list to add their own overrides; the getters, actions and snapshot
         * pruning are generated from it by ./trackOverrides.ts
         */
        get trackOverrides(): readonly TrackOverride[] {
          return FEATURE_DISPLAY_TRACK_OVERRIDES
        },
      }
      return trackOverrideViews(
        views,
        FEATURE_DISPLAY_TRACK_OVERRIDES,
        self,
      ) as typeof views & FeatureDisplayOverrideViews
    })
    .views(self => ({
      /**
       * #getter
       */
      get rendererConfig() {
        return withTrackOverrides(
          self.trackOverrides,
          self,
          getConf(self, ['renderer']) || {},
        )
      },
    }))

    .actions(self => ({
      /**
       * #action
       */
      setJexlFilters(f?: string[]) {
        self.jexlFiltersSetting = cast(f)
      },
      /**
       * #action
       */
      setFeatureUnderMouse(feat?: Feature) {
        self.featureUnderMouseVolatile = feat
      },
      ...trackOverrideActions(
        {} as FeatureDisplayOverrideActions,
        FEATURE_DISPLAY_TRACK_OVERRIDES,
        self,
      ),
    }))
    .views(self => ({
      /**
       * #getter
       * Override featureUnderMouse to return the volatile feature
       * which is fetched asynchronously via CoreGetFeatureDetails
       */
      get featureUnderMouse() {
        return self.featureUnderMouseVolatile
      },
    }))
    .actions(self => ({
      /**
       * #action
       * Fetch full feature details through CoreGetFeatureDetails, with a small
       * LRU cache and in-flight de-duplication. Shared by the hover tooltip
       * reaction and by feature clicks so repeated interactions with the same
       * feature never issue a second RPC.
       */
      async fetchFeatureDetails(featureId: string) {
        const cached = self.featureDetailsCache.get(featureId)
        if (cached) {
          // refresh LRU order
          self.featureDetailsCache.delete(featureId)
          self.featureDetailsCache.set(featureId, cached)
          return cached
        }

        const pending = self.pendingFeatureDetails.get(featureId)
        if (pending) {
          return pending
        }

        const session = getSession(self)
        const { parentTrack } = self
        const promise = fetchFeatureByIdRpc({
          rpcManager: session.rpcManager,
          sessionId: getRpcSessionId(self),
          trackId: parentTrack.id,
          rendererType: self.rendererTypeName,
          featureId,
        })
          .then(feature => {
            if (feature) {
              self.featureDetailsCache.set(featureId, feature)
              if (self.featureDetailsCache.size > MAX_FEATURE_DETAILS_CACHE) {
                const oldest = self.featureDetailsCache.keys().next().value
                if (oldest !== undefined) {
                  self.featureDetailsCache.delete(oldest)
                }
              }
            }
            return feature
          })
          .finally(() => {
            self.pendingFeatureDetails.delete(featureId)
          })

        self.pendingFeatureDetails.set(featureId, promise)
        return promise
      },
      /**
       * #action
       */
      clearFeatureDetailsCache() {
        self.featureDetailsCache.clear()
        self.pendingFeatureDetails.clear()
      },
    }))
    .views(self => {
      const {
        renderProps: superRenderProps,
        renderingProps: superRenderingProps,
      } = self
      return {
        /**
         * #method
         */
        renderProps() {
          const superProps = superRenderProps()
          return {
            ...(superProps as Omit<typeof superProps, symbol>),
            config: self.rendererConfig,
            filters: new SerializableFilterChain({
              filters: self.activeFilters(),
            }),
            sequenceAdapter: self.sequenceAdapter,
          }
        },

        /**
         * #method
         */
        renderingProps() {
          const superProps = superRenderingProps()
          const session = getSession(self)
          return {
            ...superProps,
            async onFeatureClick(_: unknown, featureId?: string) {
              const f = featureId || self.featureIdUnderMouse
              if (!f) {
                self.clearFeatureSelection()
                return
              }
              try {
                const feature = await self.fetchFeatureDetails(f)
                if (isAlive(self) && feature) {
                  self.selectFeature(feature)
                }
              } catch (e) {
                console.error(e)
                session.notifyError(`${e}`, e)
              }
            },
          }
        },

        /**
         * #method
         */
        filterMenuItems(): MenuItem[] {
          return [
            {
              label: 'Edit filters...',
              onClick: () => {
                getSession(self).queueDialog(handleClose => [
                  AddFiltersDialog,
                  {
                    model: self,
                    handleClose,
                  },
                ])
              },
            },
          ]
        },

        /**
         * #method
         * Style items appended to the "Show..." menu. Subclasses override
         * this instead of locating the submenu by label: a label lookup
         * silently drops its items when the parent menu changes, while an
         * override point cannot.
         */
        featureStyleMenuItems(): MenuItem[] {
          return []
        },

        /**
         * #method
         * Menu entries inserted after "Show..." and before "Display
         * mode". Subclasses add color/appearance menus here; the default is
         * empty so displays with a fixed palette do not get the entry.
         */
        colorMenuItems(): MenuItem[] {
          return []
        },
      }
    })
    .views(self => {
      const { trackMenuItems: superTrackMenuItems } = self
      return {
        /**
         * #method
         */
        trackMenuItems(): MenuItem[] {
          return [
            ...superTrackMenuItems(),
            {
              label: 'Show...',
              icon: VisibilityIcon,
              subMenu: [
                {
                  label: 'Show tooltips',
                  type: 'checkbox',
                  checked: self.showTooltipsEnabled,
                  onClick: () => {
                    self.setShowTooltips(!self.showTooltipsEnabled)
                  },
                },
                {
                  label: 'Show labels',
                  type: 'checkbox',
                  checked: self.showLabels,
                  onClick: () => {
                    self.toggleShowLabels()
                  },
                },
                {
                  label: 'Show descriptions',
                  type: 'checkbox',
                  checked: self.showDescriptions,
                  onClick: () => {
                    self.toggleShowDescriptions()
                  },
                },
                ...self.featureStyleMenuItems(),
              ],
            },
            ...self.colorMenuItems(),
            {
              label: 'Display mode',
              icon: VisibilityIcon,
              subMenu: [
                'normal',
                'compact',
                'reducedRepresentation',
                'collapse',
              ].map(val => ({
                label: val,
                type: 'radio' as const,
                checked: self.displayMode === val,
                onClick: () => {
                  self.setDisplayMode(val)
                },
              })),
            },
            {
              label: 'Set max layout height',
              onClick: () => {
                getSession(self).queueDialog(handleClose => [
                  SetMaxHeightDialog,
                  {
                    model: self,
                    handleClose,
                  },
                ])
              },
            },
            {
              label: 'Filter by...',
              icon: ClearAllIcon,
              subMenu: self.filterMenuItems(),
            },
          ]
        },
      }
    })
    .actions(self => ({
      afterAttach() {
        // Set up a reaction to fetch feature details when hovering
        // This enables custom mouseover jexl expressions that use get(feature, ...)
        //
        // The derivation returns the hovered feature id only while tooltips
        // are enabled, so hovering a dense track with tooltips off (or with
        // the tooltip setting toggled off) does not hit the RPC at all.
        addDisposer(
          self,
          reaction(
            () =>
              self.showTooltipsEnabled ? self.featureIdUnderMouse : undefined,
            async featureId => {
              if (!featureId) {
                self.setFeatureUnderMouse(undefined)
                return
              }

              try {
                const feature = await self.fetchFeatureDetails(featureId)

                // Only set if still alive and feature ID hasn't changed
                if (
                  isAlive(self) &&
                  feature &&
                  self.featureIdUnderMouse === featureId
                ) {
                  self.setFeatureUnderMouse(feature)
                }
              } catch (e) {
                // Silently ignore errors for mouseover - don't spam console
              }
            },
            { delay: 50, name: 'LinearFeatureDisplayMouseoverReaction' },
          ),
        )
      },
    }))
    .postProcessSnapshot(snap => {
      // eslint-disable-next-line @typescript-eslint/no-unnecessary-condition
      if (!snap) {
        return snap
      }
      const { jexlFiltersSetting, ...rest } = snap as Omit<typeof snap, symbol>
      return {
        ...pruneTrackOverrides(FEATURE_DISPLAY_TRACK_OVERRIDES, rest),
        ...(jexlFiltersSetting?.length ? { jexlFiltersSetting } : {}),
      } as typeof snap
    })
}

export type LinearFeatureDisplayStateModel = ReturnType<
  typeof stateModelFactory
>
export type LinearFeatureDisplayModel = Instance<LinearFeatureDisplayStateModel>

export default stateModelFactory
