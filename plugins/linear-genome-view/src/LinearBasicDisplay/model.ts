/**
 * Everything the composed display understands: the base feature display
 * overrides plus the ones above. The base model merges whatever the
 * `trackOverrides` view returns into `rendererConfig`.
 */
const ALL_TRACK_OVERRIDES = [
  ...FEATURE_DISPLAY_TRACK_OVERRIDES,
  ...BASIC_DISPLAY_TRACK_OVERRIDES,
]

/**
 * Getters generated from BASIC_DISPLAY_TRACK_OVERRIDES. Declared as an
 * interface so call sites stay typed and so the state model docs keep listing
 * them (the runtime implementation is generated by trackOverrideViews).
 */
interface BasicDisplayOverrideViews {
  /**
   * #getter
   * Gene glyph mode (all, longest, longestCoding). Falls back to
   * renderer.geneGlyphMode when the track override is not set
   */
  readonly geneGlyphMode: string
  /**
   * #getter
   * Subfeature label mode (none, below, overlay). Falls back to
   * renderer.subfeatureLabels when the track override is not set
   */
  readonly subfeatureLabels: string
  /**
   * #getter
   * Label placement (left, below). Falls back to renderer.labelPlacement when
   * the track override is not set
   */
  readonly labelPlacement: string
  /**
   * #getter
   * Whether to draw directional chevrons on introns. Falls back to
   * renderer.displayDirectionalChevrons when the track override is not set
   */
  readonly displayDirectionalChevrons: boolean
  /**
   * #getter
   * How feature colors are chosen (default, featureField, score, strand,
   * type). Falls back to renderer.colorScheme when the track override is not
   * set
   */
  readonly colorScheme: string
  /**
   * #getter
   * Continuous palette used by colorScheme "score". Falls back to
   * renderer.scorePalette when the track override is not set
   */
  readonly scorePalette: string
  /**
   * #getter
   * Categorical palette used by colorScheme "type". Falls back to
   * renderer.typePalette when the track override is not set
   */
  readonly typePalette: string
}

/** Actions generated from BASIC_DISPLAY_TRACK_OVERRIDES */
interface BasicDisplayOverrideActions {
  /**
   * #action
   * Set the gene glyph mode
   */
  setGeneGlyphMode(val: string): void
  /**
   * #action
   * Set the subfeature label mode
   */
  setSubfeatureLabels(val: string): void
  /**
   * #action
   * Set the label placement (left or below)
   */
  setLabelPlacement(val: string): void
  /**
   * #action
   * Toggle directional chevrons on introns
   */
  toggleDisplayDirectionalChevrons(): void
  /**
   * #action
   * Set how feature colors are chosen
   */
  setColorScheme(val: string): void
  /**
   * #action
   * Set the continuous palette used by the score color scheme
   */
  setScorePalette(val: string): void
  /**
   * #action
   * Set the categorical palette used by the type color scheme
   */
  setTypePalette(val: string): void
}

/** The subset of the display the color menu helpers need */
interface ColorMenuModel {
  colorScheme: string
  scorePalette: string
  typePalette: string
  showLegend?: boolean
  setColorScheme(val: string): void
  setScorePalette(val: string): void
  setTypePalette(val: string): void
  setShowLegend(val: boolean): void
}

function paletteItems(
  names: string[],
  current: string,
  onSelect: (name: string) => void,
): MenuItem[] {
  return names.map(name => ({
    label: name,
    type: 'radio' as const,
    checked: current === name,
    onClick: () => {
      onSelect(name)
    },
  }))
}

/**
 * The "Color by..." submenu: pick where the color comes from, then (only for
 * the scheme that uses one) the palette, then whether to show the legend.
 * Everything else about a color scheme (which attribute holds the score, fixed
 * vs automatic range, linear vs quantile) stays in the track config: it is set
 * once per track, not per view, so it would only add noise to the menu.
 */
function colorByMenu(self: ColorMenuModel): MenuItem {
  const paletteMenu =
    self.colorScheme === 'score'
      ? {
          label: 'Palette',
          subMenu: paletteItems(
            getAllContinuousPaletteNames(),
            self.scorePalette,
            name => {
              self.setScorePalette(name)
            },
          ),
        }
      : self.colorScheme === 'type'
        ? {
            label: 'Palette',
            subMenu: paletteItems(
              getAllCategoricalPaletteNames(),
              self.typePalette,
              name => {
                self.setTypePalette(name)
              },
            ),
          }
        : undefined

  return {
    label: 'Color by...',
    icon: PaletteIcon,
    subMenu: [
      ...COLOR_SCHEME_ITEMS.map(({ value, label }) => ({
        label,
        type: 'radio' as const,
        checked: self.colorScheme === value,
        onClick: () => {
          self.setColorScheme(value)
        },
      })),
      ...(paletteMenu ? [{ type: 'divider' as const }, paletteMenu] : []),
      ...(hasColorLegend(self.colorScheme)
        ? [
            { type: 'divider' as const },
            {
              label: 'Show legend',
              type: 'checkbox' as const,
              checked: self.showLegend ?? false,
              onClick: () => {
                self.setShowLegend(!(self.showLegend ?? false))
              },
            },
          ]
        : []),
    ],
  }
}

/**
 * #stateModel LinearBasicDisplay
 * #category display
 * Used by `FeatureTrack`, has simple settings like "show/hide feature labels",
 * plus gene glyph display options.
 *
 * extends
 * - [LinearFeatureDisplay](../linearfeaturedisplay)
 */
function stateModelFactory(configSchema: AnyConfigurationSchemaType) {
  return types
    .compose(
      'LinearBasicDisplay',
      LinearFeatureDisplayModelFactory(configSchema),
      types.model({
        /**
         * #property
         */
        type: types.literal('LinearBasicDisplay'),
        /**
         * #property
         */
        trackGeneGlyphMode: types.maybe(types.string),
        /**
         * #property
         */
        trackSubfeatureLabels: types.maybe(types.string),
        /**
         * #property
         */
        trackLabelPlacement: types.maybe(types.string),
        /**
         * #property
         */
        trackDisplayDirectionalChevrons: types.maybe(types.boolean),
        /**
         * #property
         */
        trackColorScheme: types.maybe(types.string),
        /**
         * #property
         */
        trackScorePalette: types.maybe(types.string),
        /**
         * #property
         */
        trackTypePalette: types.maybe(types.string),
        /**
         * #property
         */
        configuration: ConfigurationReference(configSchema),
      }),
    )
    .views(self => {
      const views = {
        /**
         * #getter
         * Base feature display overrides plus the gene/label ones
         */
        get trackOverrides(): readonly TrackOverride[] {
          return ALL_TRACK_OVERRIDES
        },
      }
      return trackOverrideViews(
        views,
        BASIC_DISPLAY_TRACK_OVERRIDES,
        self,
      ) as typeof views & BasicDisplayOverrideViews
    })
    .actions(self => ({
      ...trackOverrideActions(
        {} as BasicDisplayOverrideActions,
        BASIC_DISPLAY_TRACK_OVERRIDES,
        self,
      ),
    }))
    .views(self => ({
      /**
       * #getter
       * Legend rows for the active color scheme, built from the data the
       * renderer reported for the visible blocks (score range, feature type
       * counts). Cached by MobX until a block finishes rendering or the color
       * config changes.
       */
      get colorLegend(): LegendItem[] {
        const blockData = [...self.blockState.values()].map(
          block => block.legendData as FeatureColorLegendData | undefined,
        )
        return buildColorLegend(
          {
            scheme: self.colorScheme,
            scorePalette: self.scorePalette,
            scoreScale: getConf(self, ['renderer', 'scoreScale']) as string,
            scoreAutoRange: getConf(self, [
              'renderer',
              'scoreAutoRange',
            ]) as boolean,
            scoreMin: getConf(self, ['renderer', 'scoreMin']) as number,
            scoreMax: getConf(self, ['renderer', 'scoreMax']) as number,
            typePalette: self.typePalette,
          },
          mergeFeatureColorLegendData(blockData),
        )
      },
    }))
    .views(self => ({
      /**
       * #method
       * Legend shown by BaseLinearDisplay when "Show legend" is enabled
       */
      legendItems() {
        return self.colorLegend
      },
    }))
    .views(self => {
      const { filterMenuItems: superFilterMenuItems } = self
      return {
        filterMenuItems() {
          const filters = self.activeFilters()
          return [
            {
              label: 'Show only genes',
              type: 'checkbox',
              checked: filters.includes(GENE_TYPE_FILTER),
              onClick: () => {
                if (filters.includes(GENE_TYPE_FILTER)) {
                  self.setJexlFilters(
                    filters.filter(f => f !== GENE_TYPE_FILTER),
                  )
                } else {
                  self.setJexlFilters([...filters, GENE_TYPE_FILTER])
                }
              },
            },
            ...superFilterMenuItems(),
          ]
        },

        /**
         * #method
         * Gene/label style options appended to the "Show..." menu by the
         * base display's featureStyleMenuItems() hook
         */
        featureStyleMenuItems(): MenuItem[] {
          return [
            {
              label: 'Show chevrons',
              type: 'checkbox',
              checked: self.displayDirectionalChevrons,
              onClick: () => {
                self.toggleDisplayDirectionalChevrons()
              },
            },
            {
              label: 'Subfeature labels',
              subMenu: ['none', 'below', 'overlay'].map(val => ({
                label: val,
                type: 'radio' as const,
                checked: self.subfeatureLabels === val,
                onClick: () => {
                  self.setSubfeatureLabels(val)
                },
              })),
            },
            {
              label: 'Label placement',
              subMenu: [
                { value: 'left', label: 'Left of feature' },
                { value: 'below', label: 'Below feature' },
              ].map(({ value, label }) => ({
                label,
                type: 'radio' as const,
                checked: self.labelPlacement === value,
                onClick: () => {
                  self.setLabelPlacement(value)
                },
              })),
            },
            {
              label: 'Gene glyph',
              subMenu: [
                {
                  value: 'all',
                  label: 'All transcripts',
                },
                {
                  value: 'longest',
                  label: 'Longest transcript',
                },
                {
                  value: 'longestCoding',
                  label: 'Longest coding transcript',
                },
              ].map(({ value, label }) => ({
                label,
                type: 'radio' as const,
                checked: self.geneGlyphMode === value,
                onClick: () => {
                  self.setGeneGlyphMode(value)
                },
              })),
            },
          ]
        },

        /**
         * #method
         * "Color by..." menu. Feature colors are rendered by
         * CanvasFeatureRenderer, so the entries only make sense here (not on
         * the shared LinearFeatureDisplay that variant tracks also extend).
         */
        colorMenuItems(): MenuItem[] {
          return [colorByMenu(self)]
        },
      }
    })
    .postProcessSnapshot(snap => {
      // eslint-disable-next-line @typescript-eslint/no-unnecessary-condition
      if (!snap) {
        return snap
      }
      return pruneTrackOverrides(
        BASIC_DISPLAY_TRACK_OVERRIDES,
        snap as Omit<typeof snap, symbol>,
      ) as typeof snap
    })
}

export type FeatureTrackStateModel = ReturnType<typeof stateModelFactory>
export type FeatureTrackModel = Instance<FeatureTrackStateModel>

export default stateModelFactory
